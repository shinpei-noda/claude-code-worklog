#!/usr/bin/env python3
"""Archive Claude Code session summaries and render them as a Schedule-X calendar.

Usage:
  worklog.py sync     # scan all transcripts under ~/.claude/projects and update the archive
  worklog.py build    # render calendar.html from the archive
  worklog.py hook     # SessionEnd hook: read hook JSON from stdin, sync that transcript, build
"""

import glob
import json
import os
import sys
import tempfile
from datetime import datetime, timedelta

CLAUDE_DIR = os.path.expanduser("~/.claude")
PROJECTS_DIR = os.path.join(CLAUDE_DIR, "projects")
WORKLOG_DIR = os.path.join(CLAUDE_DIR, "worklog")
ARCHIVE_PATH = os.path.join(WORKLOG_DIR, "sessions.jsonl")
CALENDAR_PATH = os.path.join(WORKLOG_DIR, "calendar.html")
TEMPLATE_PATH = os.path.join(WORKLOG_DIR, "calendar.template.html")

# Activity gaps longer than this split a session into separate calendar events.
SEGMENT_GAP = timedelta(minutes=30)
# Short segments are stretched to this length so they stay visible in the calendar.
MIN_EVENT_LENGTH = timedelta(minutes=15)
PROMPT_PREVIEW_LENGTH = 300

# User messages starting with these are generated by the harness, not typed by the user.
NON_PROMPT_PREFIXES = (
    "<local-command-",
    "<task-notification",
    "<command-message",
    "<system-reminder",
    "This session is being continued from a previous",
)


def parse_time(value):
    return datetime.fromisoformat(value.replace("Z", "+00:00")).astimezone()


def prompt_text(entry):
    """Return the user-typed text of a transcript entry, or None if it is not a prompt."""
    if entry.get("type") != "user" or entry.get("isSidechain") or entry.get("isMeta"):
        return None
    content = (entry.get("message") or {}).get("content")
    if isinstance(content, list):
        texts = [c.get("text", "") for c in content if isinstance(c, dict) and c.get("type") == "text"]
        content = "\n".join(texts) if texts else None
    if not isinstance(content, str) or not content.strip():
        return None
    text = content.strip()
    if text.startswith(NON_PROMPT_PREFIXES):
        return None
    if text.startswith("<command-name>"):
        # Slash command: keep only "/name args".
        name = text.split("<command-name>", 1)[1].split("</command-name>", 1)[0]
        args = ""
        if "<command-args>" in text:
            args = text.split("<command-args>", 1)[1].split("</command-args>", 1)[0]
        return f"{name} {args}".strip()
    return text


def summarize_transcript(path):
    """Build a session summary from a transcript JSONL file. Returns None if it has no activity."""
    session_id = os.path.splitext(os.path.basename(path))[0]
    title = None
    cwd = None
    branches = []
    activity = []  # (time, is_prompt)
    first_prompt = None

    with open(path, encoding="utf-8") as f:
        for line in f:
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                continue
            if entry.get("type") == "ai-title" and entry.get("aiTitle"):
                title = entry["aiTitle"]
            if entry.get("isSidechain"):
                continue
            if entry.get("cwd"):
                cwd = entry["cwd"]
            branch = entry.get("gitBranch")
            if branch and branch != "HEAD" and branch not in branches:
                branches.append(branch)
            if not entry.get("timestamp") or entry.get("type") not in ("user", "assistant"):
                continue
            text = prompt_text(entry)
            if text and (first_prompt is None or first_prompt.startswith("/")):
                # Prefer a typed prompt over slash commands such as /clear or /model.
                if first_prompt is None or not text.startswith("/"):
                    first_prompt = text[:PROMPT_PREVIEW_LENGTH]
            activity.append((parse_time(entry["timestamp"]), text is not None))

    if not activity or not any(is_prompt for _, is_prompt in activity):
        return None

    activity.sort(key=lambda a: a[0])
    segments = []
    for time, is_prompt in activity:
        if segments and time - segments[-1]["end"] <= SEGMENT_GAP:
            segments[-1]["end"] = time
        else:
            segments.append({"start": time, "end": time, "prompts": 0})
        if is_prompt:
            segments[-1]["prompts"] += 1

    return {
        "session_id": session_id,
        "cwd": cwd,
        "project": os.path.basename(cwd) if cwd else os.path.basename(os.path.dirname(path)),
        "branches": branches,
        "title": title or (first_prompt or "(untitled)").splitlines()[0][:60],
        "first_prompt": first_prompt,
        "segments": [
            {"start": s["start"].isoformat(), "end": s["end"].isoformat(), "prompts": s["prompts"]}
            for s in segments
        ],
    }


def load_archive():
    archive = {}
    if os.path.exists(ARCHIVE_PATH):
        with open(ARCHIVE_PATH, encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    record = json.loads(line)
                    archive[record["session_id"]] = record
    return archive


def atomic_write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=os.path.dirname(path))
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(text)
    os.chmod(tmp, 0o600)
    os.replace(tmp, path)


def save_archive(archive):
    records = sorted(archive.values(), key=lambda r: r["segments"][0]["start"])
    atomic_write(ARCHIVE_PATH, "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records))


def sync(paths):
    archive = load_archive()
    for path in paths:
        summary = summarize_transcript(path)
        if summary:
            archive[summary["session_id"]] = summary
    save_archive(archive)
    return archive


def all_transcripts():
    # Only top-level files; subagent transcripts live in per-session subdirectories.
    return glob.glob(os.path.join(PROJECTS_DIR, "*", "*.jsonl"))


def format_for_calendar(time):
    return time.strftime("%Y-%m-%d %H:%M")


def build(archive):
    projects = sorted({r["project"] for r in archive.values()})
    calendar_ids = {project: f"p{i}" for i, project in enumerate(projects)}
    events = []
    for record in archive.values():
        for index, segment in enumerate(record["segments"]):
            start = parse_time(segment["start"])
            end = max(parse_time(segment["end"]), start + MIN_EVENT_LENGTH)
            events.append({
                "id": f"{record['session_id']}-{index}",
                "title": record["title"],
                "start": format_for_calendar(start),
                "end": format_for_calendar(end),
                "calendarId": calendar_ids[record["project"]],
                "sessionId": record["session_id"],
                "project": record["project"],
                "cwd": record.get("cwd"),
                "branches": record.get("branches", []),
                "prompts": segment["prompts"],
                "firstPrompt": record.get("first_prompt"),
            })
    data = {
        "generatedAt": datetime.now().astimezone().strftime("%Y-%m-%d %H:%M"),
        "projects": [{"name": p, "calendarId": calendar_ids[p]} for p in projects],
        "events": events,
    }
    # Escape "<" so prompt text cannot close the surrounding <script> element.
    payload = json.dumps(data, ensure_ascii=False).replace("<", "\\u003c")
    with open(TEMPLATE_PATH, encoding="utf-8") as f:
        html = f.read().replace("__WORKLOG_DATA__", payload)
    atomic_write(CALENDAR_PATH, html)


def main():
    command = sys.argv[1] if len(sys.argv) > 1 else "sync"
    if command == "sync":
        archive = sync(all_transcripts())
        build(archive)
        print(f"{len(archive)} sessions -> {CALENDAR_PATH}")
    elif command == "build":
        build(load_archive())
        print(CALENDAR_PATH)
    elif command == "hook":
        payload = json.load(sys.stdin)
        path = payload.get("transcript_path")
        build(sync([path] if path and os.path.exists(path) else []))
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
