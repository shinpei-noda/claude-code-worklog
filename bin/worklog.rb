#!/usr/bin/env ruby
# frozen_string_literal: true

# Archive Claude Code session summaries and render them as a Schedule-X calendar.
#
# The output (sessions.jsonl, calendar.html) is byte-compatible with the former
# Python implementation, so helpers below mimic Python semantics where Ruby differs
# (truthiness, str.strip, str.splitlines, json.dumps formatting, stable sort).

require "erb"
require "fileutils"
require "json"
require "tempfile"
require "time"

USAGE = <<~TEXT
  Archive Claude Code session summaries and render them as a Schedule-X calendar.

  Usage:
    worklog.rb sync     # scan all transcripts under ~/.claude/projects and update the archive
    worklog.rb build    # render calendar.html from the archive
    worklog.rb hook     # SessionEnd hook: read hook JSON from stdin, sync that transcript, build
TEXT

CLAUDE_DIR = File.join(Dir.home, ".claude")
PROJECTS_DIR = File.join(CLAUDE_DIR, "projects")
WORKLOG_DIR = File.join(CLAUDE_DIR, "worklog")
ARCHIVE_PATH = File.join(WORKLOG_DIR, "sessions.jsonl")
CALENDAR_PATH = File.join(WORKLOG_DIR, "calendar.html")
TEMPLATE_PATH = File.join(WORKLOG_DIR, "calendar.html.erb")

# Activity gaps longer than this (seconds) split a session into separate calendar events.
SEGMENT_GAP = 30 * 60
# Short segments are stretched to this length (seconds) so they stay visible in the calendar.
MIN_EVENT_LENGTH = 15 * 60
PROMPT_PREVIEW_LENGTH = 300

# User messages starting with these are generated by the harness, not typed by the user.
NON_PROMPT_PREFIXES = [
  "<local-command-",
  "<task-notification",
  "<command-message",
  "<system-reminder",
  "This session is being continued from a previous",
].freeze

# Characters Python's str.isspace() treats as whitespace.
PY_WHITESPACE = "\t\n\v\f\r\u001c-\u001f \u0085   -     　"
PY_STRIP_PATTERN = /\A[#{PY_WHITESPACE}]+|[#{PY_WHITESPACE}]+\z/
# Line boundaries recognized by Python's str.splitlines().
PY_LINE_BREAK = /\r\n|[\n\r\v\f\u001c\u001d\u001e\u0085  ]/

def truthy?(value)
  !(value.nil? || value == false || value == 0 || ((value.is_a?(String) || value.is_a?(Array) || value.is_a?(Hash)) && value.empty?))
end

def py_strip(text)
  text.gsub(PY_STRIP_PATTERN, "")
end

def py_basename(path)
  path[(path.rindex("/") || -1) + 1..]
end

def py_dirname(path)
  head = path[0, (path.rindex("/") || -1) + 1]
  head.match?(%r{\A/*\z}) ? head : head.sub(%r{/+\z}, "")
end

def py_splitext_root(path)
  sep_index = path.rindex("/") || -1
  dot_index = path.rindex(".") || -1
  return path unless dot_index > sep_index

  path[sep_index + 1...dot_index].match?(/[^.]/) ? path[0...dot_index] : path
end

# Serialize like Python's json.dumps(obj, ensure_ascii=False).
def py_json(value)
  case value
  when Hash then "{#{value.map { |k, v| "#{py_json(k.to_s)}: #{py_json(v)}" }.join(', ')}}"
  when Array then "[#{value.map { |v| py_json(v) }.join(', ')}]"
  when String then py_json_string(value)
  when nil then "null"
  else value.to_s
  end
end

JSON_ESCAPES = { '"' => '\\"', "\\" => "\\\\", "\n" => '\\n', "\r" => '\\r', "\t" => '\\t', "\b" => '\\b', "\f" => '\\f' }.freeze

def py_json_string(text)
  escaped = text.gsub(/["\\\u0000-\u001f]/) { |c| JSON_ESCAPES[c] || format("\\u%04x", c.ord) }
  %("#{escaped}")
end

def parse_json(text)
  JSON.parse(text, allow_nan: true)
end

def parse_time(value)
  time = Time.iso8601(value.gsub("Z", "+00:00")).localtime
  # Python datetime keeps microseconds only.
  Time.at(time.to_i, time.usec, :usec).localtime
end

# Format like Python's datetime.isoformat() for an aware datetime.
def isoformat(time)
  fraction = time.usec.zero? ? "" : format(".%06d", time.usec)
  time.strftime("%Y-%m-%dT%H:%M:%S#{fraction}%:z")
end

# Return the user-typed text of a transcript entry, or nil if it is not a prompt.
def prompt_text(entry)
  return nil if entry["type"] != "user" || truthy?(entry["isSidechain"]) || truthy?(entry["isMeta"])

  message = entry["message"]
  content = (truthy?(message) ? message : {})["content"]
  if content.is_a?(Array)
    texts = content.select { |c| c.is_a?(Hash) && c["type"] == "text" }.map { |c| c.fetch("text", "") }
    content = texts.empty? ? nil : texts.join("\n")
  end
  return nil if !content.is_a?(String) || py_strip(content).empty?

  text = py_strip(content)
  return nil if text.start_with?(*NON_PROMPT_PREFIXES)

  if text.start_with?("<command-name>")
    # Slash command: keep only "/name args".
    name = text.partition("<command-name>")[2].partition("</command-name>")[0]
    args = ""
    args = text.partition("<command-args>")[2].partition("</command-args>")[0] if text.include?("<command-args>")
    return py_strip("#{name} #{args}")
  end
  text
end

# Build a session summary from a transcript JSONL file. Returns nil if it has no activity.
def summarize_transcript(path)
  session_id = py_splitext_root(py_basename(path))
  title = nil
  cwd = nil
  branches = []
  activity = [] # [time, is_prompt]
  first_prompt = nil

  File.foreach(path, encoding: "UTF-8") do |line|
    begin
      entry = parse_json(line)
    rescue JSON::ParserError
      next
    end
    title = entry["aiTitle"] if entry["type"] == "ai-title" && truthy?(entry["aiTitle"])
    next if truthy?(entry["isSidechain"])

    cwd = entry["cwd"] if truthy?(entry["cwd"])
    branch = entry["gitBranch"]
    branches << branch if truthy?(branch) && branch != "HEAD" && !branches.include?(branch)
    next if !truthy?(entry["timestamp"]) || !%w[user assistant].include?(entry["type"])

    text = prompt_text(entry)
    if truthy?(text) && (first_prompt.nil? || first_prompt.start_with?("/"))
      # Prefer a typed prompt over slash commands such as /clear or /model.
      first_prompt = text[0, PROMPT_PREVIEW_LENGTH] if first_prompt.nil? || !text.start_with?("/")
    end
    activity << [parse_time(entry["timestamp"]), !text.nil?]
  end

  return nil if activity.empty? || activity.none? { |_, is_prompt| is_prompt }

  segments = []
  activity.sort_by.with_index { |(time, _), i| [time, i] }.each do |time, is_prompt|
    if !segments.empty? && time.to_r - segments.last[:end].to_r <= SEGMENT_GAP
      segments.last[:end] = time
    else
      segments << { start: time, end: time, prompts: 0 }
    end
    segments.last[:prompts] += 1 if is_prompt
  end

  {
    "session_id" => session_id,
    "cwd" => cwd,
    "project" => truthy?(cwd) ? py_basename(cwd) : py_basename(py_dirname(path)),
    "branches" => branches,
    "title" => truthy?(title) ? title : (truthy?(first_prompt) ? first_prompt : "(untitled)").split(PY_LINE_BREAK, 2)[0][0, 60],
    "first_prompt" => first_prompt,
    "segments" => segments.map { |s| { "start" => isoformat(s[:start]), "end" => isoformat(s[:end]), "prompts" => s[:prompts] } },
  }
end

def load_archive
  archive = {}
  return archive unless File.exist?(ARCHIVE_PATH)

  File.foreach(ARCHIVE_PATH, encoding: "UTF-8") do |line|
    next if py_strip(line).empty?

    record = parse_json(line)
    archive[record["session_id"]] = record
  end
  archive
end

def atomic_write(path, text)
  dir = File.dirname(path)
  FileUtils.mkdir_p(dir)
  file = Tempfile.create("tmp", dir)
  file.write(text)
  file.close
  File.chmod(0o600, file.path)
  File.rename(file.path, path)
end

def save_archive(archive)
  records = archive.values.sort_by.with_index { |r, i| [r["segments"][0]["start"], i] }
  atomic_write(ARCHIVE_PATH, records.map { |r| "#{py_json(r)}\n" }.join)
end

def sync(paths)
  archive = load_archive
  paths.each do |path|
    summary = summarize_transcript(path)
    archive[summary["session_id"]] = summary if summary
  end
  save_archive(archive)
  archive
end

def all_transcripts
  # Only top-level files; subagent transcripts live in per-session subdirectories.
  Dir.glob(File.join(PROJECTS_DIR, "*", "*.jsonl"), sort: false)
end

def format_for_calendar(time)
  time.strftime("%Y-%m-%d %H:%M")
end

def build(archive)
  projects = archive.values.map { |r| r["project"] }.uniq.sort
  calendar_ids = projects.each_with_index.to_h { |project, i| [project, "p#{i}"] }
  events = []
  archive.each_value do |record|
    record["segments"].each_with_index do |segment, index|
      start = parse_time(segment["start"])
      finish = [parse_time(segment["end"]), start + MIN_EVENT_LENGTH].max
      events << {
        "id" => "#{record['session_id']}-#{index}",
        "title" => record["title"],
        "start" => format_for_calendar(start),
        "end" => format_for_calendar(finish),
        "calendarId" => calendar_ids[record["project"]],
        "sessionId" => record["session_id"],
        "project" => record["project"],
        "cwd" => record["cwd"],
        "branches" => record.fetch("branches", []),
        "prompts" => segment["prompts"],
        "firstPrompt" => record["first_prompt"],
      }
    end
  end
  data = {
    "generatedAt" => Time.now.strftime("%Y-%m-%d %H:%M"),
    "projects" => projects.map { |p| { "name" => p, "calendarId" => calendar_ids[p] } },
    "events" => events,
  }
  # Escape "<" so prompt text cannot close the surrounding <script> element.
  payload = py_json(data).gsub("<", "\\u003c")
  template = ERB.new(File.read(TEMPLATE_PATH, encoding: "UTF-8"))
  atomic_write(CALENDAR_PATH, template.result_with_hash(payload: payload))
end

def main
  command = ARGV.fetch(0, "sync")
  case command
  when "sync"
    archive = sync(all_transcripts)
    build(archive)
    puts "#{archive.size} sessions -> #{CALENDAR_PATH}"
  when "build"
    build(load_archive)
    puts CALENDAR_PATH
  when "hook"
    payload = parse_json($stdin.read)
    path = payload["transcript_path"]
    build(sync(truthy?(path) && File.exist?(path) ? [path] : []))
  else
    abort USAGE
  end
end

main if $PROGRAM_NAME == __FILE__
